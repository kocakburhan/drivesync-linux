#!/usr/bin/env bash
set -euo pipefail
source_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
operation=install
source "$source_dir/data/install-common.sh"

if ! python3 -c 'import gi; gi.require_version("Gtk", "3.0"); gi.require_version("AyatanaAppIndicator3", "0.1"); gi.require_version("Notify", "0.7"); from gi.repository import GLib, Gio, Gtk, AyatanaAppIndicator3, Notify' 2>/dev/null; then
    echo 'Hata: Python GI, GTK 3, AyatanaAppIndicator3 ve Notify paketleri gerekli.' >&2
    exit 1
fi
if ! python3 -c 'import gi; gi.require_version("Gtk", "4.0"); gi.require_version("Adw", "1"); from gi.repository import Gtk, Adw' 2>/dev/null; then
    echo 'Hata: Ana pencere için GTK 4 ve libadwaita 1 GI paketleri gerekli.' >&2
    exit 1
fi
if [[ $with_rclone = true ]]; then
    PYTHONPATH="$source_dir/src" python3 -m drivesync.install_rclone
    export PATH="$HOME/.local/bin:$PATH"
fi
if ! PYTHONPATH="$source_dir/src" python3 - <<'PYTHON'
from drivesync.config import defaults
from drivesync.prerequisites import check_version
try:
    check_version(defaults()["rclone_path"])
except ValueError as error:
    print(error)
    raise SystemExit(1)
PYTHON
then
    echo 'Hata: rclone >= 1.66 gerekli. Kullanıcı kurulumu: ./install.sh --with-rclone' >&2
    echo 'Resmi sistem kurulumu: sudo -v ; curl https://rclone.org/install.sh | sudo bash' >&2
    echo 'Kurulum: https://github.com/kocakburhan/drivesync-linux#kurulum-adım-adım' >&2
    exit 1
fi
if ! python3 -c 'import gi; gi.require_version("Nautilus", "4.0"); from gi.repository import Nautilus' 2>/dev/null; then
    echo 'Hata: Nautilus eklentisi için python3-nautilus (GI 4.0) gerekli.' >&2
    exit 1
fi

mkdir -p -- "$prefix/lib/drivesync/drivesync" "$prefix/bin" "$unit_dir"
# Install only source files: never copy caches or local runtime state.
for module in "$source_dir"/src/drivesync/*.py; do
    install -m 644 -- "$module" "$prefix/lib/drivesync/drivesync/"
done
install -m 644 -- "$source_dir/data/style.css" "$prefix/lib/drivesync/drivesync/style.css"
mkdir -p -- "$extension_dir" "$icon_dir/scalable/emblems"
for icon in "$source_dir"/data/icons/hicolor/scalable/emblems/emblem-drivesync-*.svg; do
    install -m 644 -- "$icon" "$icon_dir/scalable/emblems/"
done
# The extension is imported as "drivesync" by nautilus-python. Give this
# module a package path too, so it cannot shadow our installed package.
python3 - "$extension_dir/drivesync.py" "$prefix/lib/drivesync/drivesync" <<'PY'
from pathlib import Path
import sys
target, package = map(Path, sys.argv[1:])
target.write_text('# Generated by DriveSync install.sh\n'
                  f'__path__ = [{str(package)!r}]\n'
                  'from drivesync.nautilus_ext import DriveSyncExtension\n', encoding='utf-8')
target.chmod(0o644)
PY
for name in drivesync-daemon drivesync-tray drivesync-cli drivesync-app; do
    install -m 755 -- "$source_dir/bin/$name" "$prefix/bin/$name"
done
mkdir -p -- "$desktop_dir" "$icon_dir/scalable/apps" "$icon_dir/symbolic/apps" "$icon_dir/scalable/status"
install -m 644 -- "$source_dir/data/io.github.kocakburhan.DriveSync.desktop" "$desktop_dir/"
install -m 644 -- "$source_dir/data/icons/hicolor/scalable/apps/io.github.kocakburhan.DriveSync.svg" "$icon_dir/scalable/apps/"
for icon in "$source_dir"/data/icons/hicolor/symbolic/apps/drivesync-*-symbolic.svg; do
    install -m 644 -- "$icon" "$icon_dir/symbolic/apps/"
done
for icon in "$source_dir"/data/icons/hicolor/scalable/status/drivesync-tray-*.svg; do
    install -m 644 -- "$icon" "$icon_dir/scalable/status/"
done
refresh_desktop_caches
python3 - "$source_dir" "$prefix" "$unit_dir" "$with_rclone" <<'PY'
import os
from pathlib import Path
import sys

source, prefix, units = map(Path, sys.argv[1:4])
select_local_rclone = sys.argv[4] == "true"
home = Path.home()

def unit_path(path):
    # Preserve %h for home-relative paths; escape systemd specifiers elsewhere.
    try:
        value = "%h/" + str(path.relative_to(home)).replace("%", "%%")
    except ValueError:
        value = str(path).replace("%", "%%")
    return value.replace("\\", "\\\\").replace('"', '\\"')

for name in ("drivesync.service", "drivesync-tray.service"):
    text = (source / "data/systemd" / name).read_text()
    text = text.replace("%h/.local", unit_path(prefix))
    # A custom XDG environment must also reach services started by systemd.
    for variable in ("XDG_CONFIG_HOME", "XDG_STATE_HOME", "XDG_DATA_HOME"):
        value = os.environ.get(variable)
        if value and Path(value).is_absolute():
            text = text.replace("Environment=PYTHONDONTWRITEBYTECODE=1",
                                f'Environment="{variable}={unit_path(Path(value))}"\n'
                                'Environment=PYTHONDONTWRITEBYTECODE=1')
    target = units / name
    target.write_text(text)
    target.chmod(0o644)

sys.path.insert(0, str(prefix / "lib/drivesync"))
from drivesync.config import edit_lock, load, save
from drivesync.paths import Paths
paths = Paths.from_env()
with edit_lock(paths):
    settings = load(paths)
    if select_local_rclone:
        # Explicit --with-rclone also selects the freshly verified binary.
        # Otherwise an existing /usr/bin/rclone setting could stay too old.
        settings["rclone_path"] = str(home / ".local/bin/rclone")
        save(paths, settings)

# Where this copy came from, for `drivesync-cli update`. Written after the files, never read here.
import re
from datetime import datetime, timezone
from drivesync.paths import write_json
version = re.search(r'^__version__ = "([^"]+)"', (source / "src/drivesync/__init__.py").read_text(encoding="utf-8"),
                    re.MULTILINE).group(1)
write_json(prefix / "lib/drivesync/install-info.json", dict(
    source_dir=str(source), version=version,
    installed_at=datetime.now(timezone.utc).isoformat(timespec="seconds")))
PY
if [[ $no_enable = false ]]; then
    systemctl --user daemon-reload
    systemctl --user enable --now drivesync.service drivesync-tray.service
fi
echo 'DriveSync kuruldu.'
echo 'Nautilus eklentisi için Dosyalar yeniden başlatılmalı: nautilus -q (açık pencereler kapanır).'
